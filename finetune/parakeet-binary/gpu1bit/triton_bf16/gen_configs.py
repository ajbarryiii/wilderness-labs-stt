"""Write configs.py from tune.py outputs (CPU only). For each mode family the faster of the in-kernel
path ("bf16x3") and the prep+plane path ("bf16x3p") per (op, tuned M) is kept, with its path.

    finetune/parakeet-binary/python -m gpu1bit.triton_bf16.gen_configs TUNE.json [TUNE.json ...]
"""
import json
import sys
from pathlib import Path

KINDS = {"qkv": ("linear", 3072, 1024), "out": ("linear", 1024, 1024), "ff_up": ("linear", 4096, 1024),
         "ff_down": ("linear", 1024, 4096), "pw1": ("conv", 2048, 1024), "pw2": ("conv", 1024, 1024)}
FAMILY = {"bf16x3": ("bf16x3", "fused"), "bf16x3p": ("bf16x3", "planes"),
          "fp16x2": ("fp16x2", "fused"), "fp16x2p": ("fp16x2", "planes")}

HEADER = '''"""Offline-tuned tiles for agent A's kernels on this RTX 5090 (400 W cap). No runtime autotuning.

Generated by gen_configs.py from: {sources}
(tune.py: real MB1 layer-0 weights, CUDA-graph replay, L2-hot; {semantics}). Keys: mode family ->
"kind:N:K" -> tuned M -> [config, measured us, path]. path "fused" = in-kernel split (_bgemm), "planes"
= prep kernel + plane GEMM (_split_rows + _pgemm). A call with M uses its band's entry: M <= 64 -> 38,
M <= 192 -> 126, else 368 (linear_pos at 2T-1 uses the linear 1024x1024 entries).
config = (BM, BN, BK, SPLIT, warps, stages, REDUCE, GROUPS, EW_DECODE).
"""
'''

FOOTER = '''

def lookup(mode: str, kind: str, n: int, k: int, m: int):
    """(config, path) tuned for this layer shape and M band, or None (caller falls back to defaults)."""
    family = mode[:-1] if mode.endswith("p") else mode
    entries = TABLE.get(family, {}).get(f"{kind}:{n}:{k}")
    if not entries:
        return None
    band = 38 if m <= 64 else 126 if m <= 192 else 368
    hit = entries.get(str(band))
    if not hit:
        return None
    config, _, path = hit
    if mode.endswith("p") and path != "planes":   # an explicit plane mode keeps its own path
        return None
    return tuple(config), path
'''


def main():
    rows = []
    for f in sys.argv[1:]:
        rows += [dict(r, source=f) for r in json.loads(Path(f).read_text())]
    table, semantics = {}, set()
    for r in rows:
        family, path = FAMILY[r["mode"]]
        kind, n, k = KINDS[r["shape"]]
        semantics.add("op semantics (norm/SiLU fused)" if r.get("semantics") and any(r["semantics"]) else "bare linear/conv")
        key, band = f"{kind}:{n}:{k}", str(r["m"])
        cur = table.setdefault(family, {}).setdefault(key, {}).get(band)
        cand = [list(r["best"]["config"]), round(r["best"]["us"], 2), path]
        if cur is None or cand[1] < cur[1]:
            table[family][key][band] = cand
    out = Path(__file__).with_name("configs.py")
    out.write_text(HEADER.format(sources=", ".join(sys.argv[1:]), semantics="; ".join(sorted(semantics)))
                   + "TABLE = " + json.dumps(table, indent=1) + "\n" + FOOTER)
    for family, shapes in table.items():
        for key, bands in shapes.items():
            print(family, key, {b: (v[1], v[2]) for b, v in bands.items()})


if __name__ == "__main__":
    main()
