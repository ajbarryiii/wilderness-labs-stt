"""The recorded x2 benchmark session (plans/x2-default.md "Recorded GPU benchmark", X5, Y4, Z2; agent H).

A thin driver over the selection-session machinery. The protocols are shared/bench.py's: P-paired encoder and
full scope over dev_24 in 6 chunks with every arm resident and balanced order, P-clips + P-memory per arm in
fresh processes in roster order then reverse order, and P-kernel. The orchestration and acceptance are
gpu1bit/rerun_timing.py's roster-file mode (quiet host before every process, 400 W and foreign-process checks
in every protocol, one gpu lock per process, attempts in per-step sidecars, a step accepted only if its
output is complete and bound, stale or rejected outputs moved to dropped/, resumable). The session freeze is
selection.write_freeze (every fingerprint source, plus the Z2 pointer pin).

ROSTER (ROOT/<run>/roster.json, written once): b1 to b6 exactly as X5 (gpu1bit/x2/bench_roster.py), with
R-expanded (b3) first as P-paired's reference process slot, the frozen pairs, the patch gpu1bit.x2.bench_patch,
the gate run and its record, the candidate selection document (path and content hash), and the P-kernel
layer variants int8_mma and int8_mma:x2 (with M1's baselines).

GUARD (before every process and before every report): the freeze verifies (sources unchanged, nothing added,
selected.json the pinned x3 document or the promoted candidate: Z2); the candidate document and the
selection in use have the roster's content hash; the gate record passed under that content; each fulldev
arm (b1 g1, b2 g3, b4 g4, b5 g5) verifies in the gate run (fulldev.check_identity) with the gate record's
identity. It returns each variant's identity (None for b3 and b6) and its label (roster id, model,
complete export identity).

BINDING: an artifact is accepted only if it names the step's protocol, run, workloads and variants and every
variant's recorded roster id, model, export, selection hash and (fulldev arms) identity equal the guard's.
REPORTS AND A13 use only ACCEPTED measurements: each step's sidecar accepted it under this roster's binding and
the output still has the accepted bytes (rerun_timing.reusable; Codex x2 c1, finding 5).

PHASES: `dev`, then the dev report (report-dev.json: labels verified, the frozen pairs with median paired
energy and latency reported separately, plain statements where b4 is worse than b6, no decision (Y4),
absolute medians, P-clips, P-memory and P-kernel tables; it marks the dev results written), then
`historical-test`: the same P-paired and P-clips protocols on M1's historical test workloads
(gpu1bit/x2/historical.py), under the runs <run>-test, <run>-test-clips1/2, refused until the dev results
are written and bound to this roster (A13); then report-test.json. Reports are regenerated byte-identically
after promotion (they record no pointer state) and refused in a third pointer state (Z2).

    gpu1bit/shared/python -m gpu1bit.x2.bench_session roster --run R --gate-run G          (CPU; writes the freeze)
    job start x2-bench --needs gpu --quiet-host --full-machine --priority normal -- \\
        gpu1bit/shared/python -m gpu1bit.x2.bench_session session --run R               (dev, report, test, report)
    gpu1bit/shared/python -m gpu1bit.x2.bench_session report --run R | report-test --run R  (CPU)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import statistics
import subprocess
from pathlib import Path

from gpu1bit.shared import env, fulldev, selection
from gpu1bit.x2 import bench_roster as BR

ROOT = env.ARTIFACTS / "x2" / "bench"
BENCH = env.ARTIFACTS / "bench"
KIND = "x2-benchmark"
VARIANTS = [BR.ROW[b]["variant"] for b in ("b3", "b1", "b2", "b4", "b5", "b6")]
PATCHES = ["gpu1bit.x2.bench_patch"]
KERNEL_IMPLS = ["int8_mma", "int8_mma:x2"]
FULLDEV_GATE = {"MB1-B-hybrid-x2": "g1", "MB1-B-hybrid-x3": "g3", "M1-x2": "g4", "M1-x3": "g5"}
PHASES = ("dev", "historical-test")
CHUNKS = ["0-3", "4-7", "8-11", "12-15", "16-19", "20-23"]
PY = str(env.SHARED / "python")
KEYS = ("median_ms", "joules_per_iteration", "average_watts")


# --- roster ------------------------------------------------------------------------------------------------

def roster_doc(run: str, gate_run: str, gate_record=None) -> dict:
    from gpu1bit.shared import seldoc
    record = Path(gate_record) if gate_record else ROOT.parent / f"gates-{gate_run}.json"
    return {"run": run, "kind": KIND,
            "label": "recorded x2 benchmark (plans/x2-default.md): b1 to b6, P-paired encoder + full on dev_24, "
                     "P-clips/P-memory forward + reverse, P-kernel; then M1's historical test workloads (A13)",
            "variants": list(VARIANTS), "reference": VARIANTS[0], "roster": BR.BENCH_ROSTER,
            "pairs": [list(p) for p in BR.PAIRS], "patches": list(PATCHES), "phase_pair": [],
            "kernel_impls": list(KERNEL_IMPLS), "gate_run": gate_run, "gate_record": str(record),
            "selection": {"path": str(seldoc.CANDIDATE), "sha256": env.sha256_file(seldoc.CANDIDATE)},
            "freeze_file": str(selection.freeze_path(run))}


def roster_sha(roster: dict) -> str:
    body = {k: v for k, v in roster.items() if k != "phase"}
    return hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest()


def roster_path(run: str, root: Path | None = None) -> Path:
    return Path(root or ROOT) / run / "roster.json"


def write_roster(doc: dict, root: Path | None = None) -> dict:
    """Written once; a different roster for the same run is refused."""
    env.require_mount()
    path = roster_path(doc["run"], root)
    if path.exists():
        old = json.loads(path.read_text())
        if old != json.loads(json.dumps(doc)):
            raise SystemExit(f"{path} is frozen with a different roster")
        return old
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(doc, indent=1) + "\n")
    return json.loads(path.read_text())


def load_roster(run: str) -> dict:
    path = roster_path(run)
    if not path.exists():
        raise SystemExit(f"no x2 benchmark roster {path}")
    doc = json.loads(path.read_text())
    if doc.get("kind") != KIND:
        raise SystemExit(f"{path} is not an x2 benchmark roster")
    return doc


# --- guard and binding -------------------------------------------------------------------------------------

def guard(roster: dict) -> dict:
    """See the module docstring; SystemExit on any problem. Same keys as selection.verify_freeze, plus
    identities, labels and identity_run (the gate run)."""
    from gpu1bit.actprec import parts
    from gpu1bit.shared import seldoc
    if not selection.freeze_path(roster["run"]).exists():
        raise SystemExit(f"no session freeze {selection.freeze_path(roster['run'])} (run `roster` first)")
    fz = selection.verify_freeze(roster["run"])
    want = roster["selection"]["sha256"]
    cand = Path(roster["selection"]["path"])
    if not cand.exists() or env.sha256_file(cand) != want:
        raise SystemExit(f"{cand} is not the roster's candidate selection document ({want[:12]})")
    if seldoc.load()["sha256"] != want:
        raise SystemExit(f"the selection document in use ({seldoc.current_path()}) is not the roster's candidate "
                         f"(set GPU1BIT_SELECTION={cand})")
    path = Path(roster["gate_record"])
    if not path.exists():
        raise SystemExit(f"no gate record {path}")
    gate = json.loads(path.read_text())
    if gate.get("pass") is not True:
        raise SystemExit(f"the gate record {path} did not pass; nothing is measured")
    if (gate.get("selection") or {}).get("sha256") != want:
        raise SystemExit(f"the gate record {path} is not under the candidate selection document")
    parts.install()
    identities = {}
    for v in roster["variants"]:
        gid = FULLDEV_GATE.get(v)
        if gid is None:
            identities[v] = None
            continue
        h = fulldev.check_identity(roster["gate_run"], v, "full")["hash"]
        if h != (gate.get("identities") or {}).get(gid):
            raise SystemExit(f"{v}: identity {h[:12]} differs from the gate record's {gid} identity")
        identities[v] = h
    labels = {}
    for v in roster["variants"]:
        bid = BR.VARIANT_TO_ID[v]
        labels[v] = {"roster_id": bid, "model": BR.ROW[bid]["model"], "export": fulldev.export_identity(BR.export_dir(bid))}
    return {**fz, "identities": identities, "references": None, "identity_run": roster["gate_run"], "labels": labels}


def info_problems(info: dict, variant: str, roster: dict, expected: dict) -> list[str]:
    probs = []
    lab = (expected.get("labels") or {}).get(variant)
    if lab is None:
        return [f"{variant}: no expected label"]
    for k in ("roster_id", "model", "export"):
        if info.get(k) != lab[k]:
            probs.append(f"{variant}: {k}")
    if info.get("selection_sha256") != roster["selection"]["sha256"]:
        probs.append(f"{variant}: selection")
    ident = (expected.get("identities") or {}).get(variant)
    if ident is not None and info.get("identity") != ident:
        probs.append(f"{variant}: identity")
    return probs


def artifact_bound(step: dict, doc: dict, roster: dict, expected: dict) -> bool:
    args = doc.get("args") or {}
    if step["kind"] == "kernel":
        return (doc.get("protocol") == "P-kernel" and args.get("run") == step["run"]
                and list(args.get("impl") or []) == list(roster["kernel_impls"]) and args.get("baselines") is True)
    if args.get("run") != step["run"] or args.get("workloads", "dev") != step["workloads"]:
        return False
    if step["kind"] == "paired":
        if not (doc.get("protocol") == "P-paired" and doc.get("scope") == step["scope"]
                and doc.get("variants") == list(roster["variants"]) and args.get("utterances") == step["range"]):
            return False
        infos = doc.get("variants_info") or {}
        return all(not info_problems(infos.get(v) or {}, v, roster, expected) for v in roster["variants"])
    if step["kind"] == "clips":
        return (doc.get("protocol") == "P-clips+P-memory" and doc.get("variant") == step["variant"]
                and not info_problems(doc.get("variant_info") or {}, step["variant"], roster, expected))
    return False


def child_env_updates(roster: dict) -> dict:
    return {"GPU1BIT_SELECTION": roster["selection"]["path"]}


# --- steps -------------------------------------------------------------------------------------------------

def require_dev_results(run: str, roster: dict | None = None, verify: bool = True) -> dict:
    """A13: the historical test workloads are used only after this run's dev results are written: the dev
    report's marker bound to this roster and, with `verify` (always, except inside the dev report itself),
    every dev step's accepted measurement verified again (_collect; Codex x2 c1, finding 5)."""
    path = ROOT / run / "report-dev.json"
    if not path.exists():
        raise SystemExit(f"A13: the dev results of x2 benchmark run {run} are not written ({path})")
    doc = json.loads(path.read_text())
    if doc.get("dev_results_written") is not True:
        raise SystemExit(f"A13: {path} does not mark the dev results written")
    roster = roster if roster is not None else load_roster(run)
    if doc.get("roster_sha256") != roster_sha(roster):
        raise SystemExit(f"A13: {path} is bound to another roster")
    if verify:
        try:
            _collect({k: v for k, v in roster.items() if k != "phase"}, "dev")
        except SystemExit as exc:
            raise SystemExit(f"A13: the dev results of {run} are not accepted measurements: {exc}") from None
    return doc


def steps(roster: dict, phase: str) -> list[dict]:
    run, variants = roster["run"], list(roster["variants"])
    disp = [PY, "-m", "gpu1bit.shared.dispatch", "--patches", ",".join(roster["patches"])]
    if phase == "dev":
        tag, prun, extra, wl = "", run, [], "dev"
    elif phase == "historical-test":
        require_dev_results(run, roster)
        tag, prun, extra, wl = "test-", f"{run}-test", ["--workloads", "historical-test", "--dev-run", run], "historical-test"
    else:
        raise ValueError(f"phase {phase!r}")
    out = []
    for scope in ("encoder", "full"):
        for rng in CHUNKS:
            a, b = (int(v) for v in rng.split("-"))
            out.append({"name": f"{tag}paired-{scope}-{rng}", "output": BENCH / prun / f"paired-{scope}-{a:02d}-{b:02d}.json",
                        "kind": "paired", "scope": scope, "range": rng, "run": prun, "workloads": wl,
                        "cmd": disp + ["bench", "paired", "--agent", "H", "--run", prun, "--scope", scope,
                                       "--variants", *variants, "--utterances", rng, *extra]})
    for order, label in ((variants, "clips1"), (variants[::-1], "clips2")):
        crun = f"{prun}-{label}"
        for v in order:
            safe = v.replace(":", "_")
            out.append({"name": f"{tag}{label}-{safe}", "output": BENCH / crun / f"clips-{safe}.json", "clips": True,
                        "kind": "clips", "label": label, "variant": v, "run": crun, "workloads": wl,
                        "cmd": disp + ["bench", "clips", "--agent", "H", "--run", crun, "--variant", v, *extra]})
    if phase == "dev":
        out.append({"name": "kernel", "output": BENCH / run / "kernel.json", "kind": "kernel", "run": run, "workloads": "dev",
                    "cmd": disp + ["bench", "kernel", "--agent", "H", "--run", run, "--impl", *roster["kernel_impls"],
                                   "--baselines"]})
    return out


# --- reports -----------------------------------------------------------------------------------------------

def _collect(roster: dict, phase: str) -> dict:
    """Every step's output of `phase`: complete, labels verified, and an ACCEPTED measurement: the
    orchestrator's sidecar accepted it under this roster's binding (roster with its phase, protocol command,
    identities, labels) and the output still has the accepted bytes (rerun_timing.reusable; Codex x2 c1,
    finding 5). SystemExit otherwise."""
    from gpu1bit import rerun_timing as RT
    rp = {**{k: v for k, v in roster.items() if k != "phase"}, "phase": phase}   # as the orchestrator binds it
    g = guard(rp)
    expected = RT.make_binding(rp, g)
    root = ROOT / roster["run"]
    docs = {}
    for st in steps(rp, phase):
        if not RT.output_complete(st):
            raise SystemExit(f"{st['name']}: output missing or incomplete ({st['output']})")
        doc = json.loads(st["output"].read_text())
        if st["kind"] != "kernel":
            infos = (doc.get("variants_info") or {}) if st["kind"] == "paired" else {st["variant"]: doc.get("variant_info") or {}}
            try:
                BR.verify_labels(infos, None if st["kind"] == "paired" else [st["variant"]])
            except ValueError as exc:
                raise SystemExit(f"{st['name']}: {exc}")
        if not artifact_bound(st, doc, roster, expected):
            probs = []
            for v, info in ((doc.get("variants_info") or {}).items() if st["kind"] == "paired"
                            else [(st.get("variant"), doc.get("variant_info") or {})]):
                probs += info_problems(info, v, roster, expected) if v else []
            raise SystemExit(f"{st['name']}: not bound to this roster, protocol and identities {probs[:6]}")
        if not RT.reusable(st, RT._sidecar(root, st), expected, rp):
            raise SystemExit(f"{st['name']}: not an accepted measurement (no accepted sidecar in {root / 'host'} bound "
                             f"to this roster, protocol and identities, or its output changed since acceptance)")
        docs[st["name"]] = (st, doc)
    return {"guard": g, "docs": docs}


def _rows(docs: dict, prefix: str, scope: str) -> list[dict]:
    rows = [r for name, (st, doc) in docs.items() if st["kind"] == "paired" and st["scope"] == scope
            and name.startswith(prefix) for r in doc["rows"]]
    rows.sort(key=lambda r: r["index"])
    if [r["index"] for r in rows] != list(range(24)):
        raise SystemExit(f"{scope}: utterances {[r['index'] for r in rows]}")
    return rows


def _medians(rows: list[dict], variants: list[str]) -> dict:
    return {v: {k: statistics.median(r["summary"][v][k] for r in rows) for k in KEYS} for v in variants}


def _clips(docs: dict) -> tuple[dict, dict]:
    memory, timing = {}, {}
    for st, doc in docs.values():
        if st["kind"] != "clips":
            continue
        v = st["variant"]
        for w in doc["workloads"]:
            c = w["record"]["id"]
            memory.setdefault(v, {})[c] = max(memory.get(v, {}).get(c, 0), int(w["process_sampled_peak_including_first_bytes"]))
            timing.setdefault(v, {}).setdefault(c, []).append({**{k: w["summary"][k] for k in KEYS}, "order": st["label"],
                                                               "text": w["hypothesis"]})
    return memory, timing


def _write(path: Path, rep: dict) -> None:
    """Write only if the content changed; an earlier different report is kept as .previous-<time>."""
    text = json.dumps(rep, indent=1, sort_keys=True) + "\n"
    if path.exists() and path.read_text() == text:
        return
    if path.exists():
        import time
        path.rename(path.with_name(f"{path.stem}.previous-{time.strftime('%Y%m%dT%H%M%S')}.json"))
    tmp = path.with_name(f"{path.name}.tmp{os.getpid()}")
    tmp.write_text(text)
    os.replace(tmp, path)


def report_dev(run: str) -> dict:
    roster = load_roster(run)
    got = _collect(roster, "dev")
    docs, g = got["docs"], got["guard"]
    full, enc = _rows(docs, "paired-full", "full"), _rows(docs, "paired-encoder", "encoder")
    memory, timing = _clips(docs)
    kernel = {}
    for row in docs["kernel"][1]["rows"]:
        for v, r in row["variants"].items():
            kernel.setdefault(v, {}).setdefault(row["op"], {})[str(row.get("clip_M", row.get("M")))] = {
                k: r.get(k) for k in ("warm_us", "cold_us", "rel_frobenius_vs_fp64")}
    rep = {"run": run, "roster_sha256": roster_sha(roster), "gate_run": roster["gate_run"], "phase": "dev",
           "descriptive_only": True,
           "rule": "plans/x2-default.md Y4: each frozen pair reports median paired energy and median latency "
                   "separately, with counts, and no automatic consequence",
           "identities": g["identities"],
           "labels": {v: {"roster_id": lab["roster_id"], "model": lab["model"], "export_path": lab["export"]["path"],
                          "export_sha256": lab["export"]["sha256"]} for v, lab in g["labels"].items()},
           "full": BR.describe_pairs(full), "encoder": BR.describe_pairs(enc),
           "absolute_median": {"full": _medians(full, roster["variants"]), "encoder": _medians(enc, roster["variants"])},
           "full_identical_to_reference": {v: sum(bool(r["checks"][v].get(f"identical_to_{roster['variants'][0]}")) for r in full)
                                           for v in roster["variants"]},
           "p_memory": memory, "p_clips": timing, "kernel": kernel, "dev_results_written": True}
    path = ROOT / run / "report-dev.json"
    _write(path, rep)
    return json.loads(path.read_text())


M1_RECORDED_24 = Path("/mnt/hd/wilderness-labs-stt/parakeet-ternary/kernel-runs/20261007T141539-cuda-pipeline/pipeline.json")
M1_RECORDED_CLIPS = Path("/mnt/hd/wilderness-labs-stt/parakeet-ternary/comparison/cuda-iteration-20261007")


def m1_recorded() -> dict:
    """M1's recorded numbers on the same historical workloads, for comparability only."""
    out = {}
    if M1_RECORDED_24.exists():
        rows = json.loads(M1_RECORDED_24.read_text())
        variants = sorted(rows[0]["summary"])
        out["utterances"] = {"source": str(M1_RECORDED_24), "sha256": env.sha256_file(M1_RECORDED_24),
                             "median": {v: {k: statistics.median(r["summary"][v][k] for r in rows) for k in KEYS} for v in variants}}
    clips = {}
    for f in sorted(M1_RECORDED_CLIPS.glob("*.json")):
        d = json.loads(f.read_text())
        clips[d.get("variant", f.stem)] = {"source": str(f), "sha256": env.sha256_file(f),
                                           "clips": {w["record"]["id"]: w.get("summary") for w in d.get("workloads", [])}}
    out["clips"] = clips
    return out


def report_test(run: str) -> dict:
    roster = load_roster(run)
    require_dev_results(run, roster)
    got = _collect(roster, "historical-test")
    docs = got["docs"]
    full, enc = _rows(docs, "test-paired-full", "full"), _rows(docs, "test-paired-encoder", "encoder")
    memory, timing = _clips(docs)
    rep = {"run": run, "roster_sha256": roster_sha(roster), "phase": "historical-test", "descriptive_only": True,
           "rule": "plans/gpu-kernel.md A13: M1's historical test workloads, after the freeze and the dev results, "
                   "for comparability with M1's recorded numbers only; nothing is selected or tuned on them",
           "full": BR.describe_pairs(full), "encoder": BR.describe_pairs(enc),
           "absolute_median": {"full": _medians(full, roster["variants"]), "encoder": _medians(enc, roster["variants"])},
           "p_memory": memory, "p_clips": timing, "m1_recorded": m1_recorded()}
    path = ROOT / run / "report-test.json"
    _write(path, rep)
    return json.loads(path.read_text())


# --- CLI ---------------------------------------------------------------------------------------------------

def _phase(run: str, phase: str, metadata: str) -> None:
    rc = subprocess.run([PY, str(env.GPU1BIT / "rerun_timing.py"), "--roster-file", str(roster_path(run)), "--phase", phase,
                         "--metadata", metadata], cwd=str(env.BINARY_DIR)).returncode
    if rc != 0:
        raise SystemExit(f"{phase} phase stopped (rc {rc}); see {ROOT / run / 'rerun_timing.log'}")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="action", required=True)
    s = sub.add_parser("roster")
    s.add_argument("--run", required=True)
    s.add_argument("--gate-run", required=True)
    for name in ("session", "report", "report-test"):
        s = sub.add_parser(name)
        s.add_argument("--run", required=True)
        if name == "session":
            s.add_argument("--metadata", default="{}")
    args = p.parse_args()
    if args.action == "roster":
        doc = write_roster(roster_doc(args.run, args.gate_run))
        fz = selection.write_freeze(args.run)
        os.environ["GPU1BIT_SELECTION"] = doc["selection"]["path"]
        guard(doc)
        print(json.dumps({"roster": str(roster_path(args.run)), "freeze": fz["freeze"], "files": fz["files"],
                          "pointer": fz.get("pointer")}))
    elif args.action == "session":
        load_roster(args.run)
        _phase(args.run, "dev", args.metadata)
        os.environ["GPU1BIT_SELECTION"] = load_roster(args.run)["selection"]["path"]
        report_dev(args.run)
        _phase(args.run, "historical-test", args.metadata)
        report_test(args.run)
        print("X2 BENCHMARK COMPLETE", flush=True)
    else:
        os.environ["GPU1BIT_SELECTION"] = load_roster(args.run)["selection"]["path"]
        rep = report_dev(args.run) if args.action == "report" else report_test(args.run)
        print(json.dumps({"full": rep["full"]["statements"], "pairs": sorted(rep["full"]["pairs"])}))


if __name__ == "__main__":
    main()
